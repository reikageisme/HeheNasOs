#!/bin/sh
# Buildroot post-build hook shared by all boards.
#   $1 = TARGET_DIR   $2 = board ("rpi3" or "x86")
set -eu
TARGET_DIR="$1"
BOARD="${2:-rpi3}"
INITTAB="$TARGET_DIR/etc/inittab"
FSTAB="$TARGET_DIR/etc/fstab"
STATE=/var/lib/hehenas
DEFAULTS="$TARGET_DIR/usr/share/hehenas/etc-default"

add_line() { grep -qF "$2" "$1" || printf '%s\n' "$2" >> "$1"; }

# --- hehenasd: supervised by init, output to syslog ---------------------------
if ! grep -q hehenasd "$INITTAB"; then
	cat >> "$INITTAB" <<'EOF'
# HeheNAS management daemon (web UI on :8080 / :8443), restarted if it exits
::respawn:/bin/sh -c '/usr/sbin/hehenasd --config /etc/hehenas/hehenasd.toml 2>&1 | /usr/bin/logger -t hehenasd; sleep 3'
EOF
fi

# --- writable state lives on the persistent partition ---------------------------
# The rootfs is read-only (Raspberry Pi A/B image); everything that changes at
# runtime is a symlink into /var/lib/hehenas or /tmp.
mkdir -p "$TARGET_DIR$STATE" "$TARGET_DIR/boot" "$TARGET_DIR/mnt" "$DEFAULTS"

printf 'hehenas\n' > "$DEFAULTS/hostname"
printf '127.0.0.1\tlocalhost\n127.0.1.1\thehenas\n' > "$DEFAULTS/hosts"
# Must match what hehenasd renders for DHCP, so the first start changes nothing.
printf '# Generated by hehenasd\nauto lo\niface lo inet loopback\n\nauto eth0\niface eth0 inet dhcp\n' > "$DEFAULTS/interfaces"
printf '# Generated by hehenasd\n' > "$DEFAULTS/exports"

for f in hostname hosts exports; do
	ln -sfn "$STATE/etc/$f" "$TARGET_DIR/etc/$f"
done
mkdir -p "$TARGET_DIR/etc/network"
ln -sfn "$STATE/etc/interfaces" "$TARGET_DIR/etc/network/interfaces"
ln -sfn /tmp/issue "$TARGET_DIR/etc/issue"
rm -rf "$TARGET_DIR/etc/ksmbd"
ln -sfn "$STATE/ksmbd" "$TARGET_DIR/etc/ksmbd"
rm -rf "$TARGET_DIR/var/lib/seedrng"
ln -sfn "$STATE/seedrng" "$TARGET_DIR/var/lib/seedrng"

# --- NFS: started on demand by hehenasd, not at boot -----------------------------
mkdir -p "$TARGET_DIR/usr/libexec/hehenas"
if [ -f "$TARGET_DIR/etc/init.d/S60nfs" ]; then
	mv "$TARGET_DIR/etc/init.d/S60nfs" "$TARGET_DIR/usr/libexec/hehenas/nfs-service"
fi

case "$BOARD" in
rpi3)
	# HDMI login prompt next to the serial console.
	add_line "$INITTAB" 'tty1::respawn:/sbin/getty -L tty1 0 vt100 # HDMI console'
	# Repair the state partition after a power cut, before it is mounted.
	if ! grep -q 'e2fsck -p /dev/mmcblk0p4' "$INITTAB"; then
		sed -i 's|^::sysinit:/bin/mount -a|::sysinit:/sbin/e2fsck -p /dev/mmcblk0p4\n&|' "$INITTAB"
	fi
	add_line "$FSTAB" "/dev/mmcblk0p4	$STATE	ext4	defaults,noatime	0	2"
	add_line "$FSTAB" "/dev/mmcblk0p1	/boot	vfat	defaults,noatime,umask=0022	0	0"
	add_line "$FSTAB" "tmpfs	/mnt	tmpfs	mode=0755,size=64k	0	0"
	rm -f "$TARGET_DIR/etc/init.d/S01persist"
	;;
x86)
	# Live ISO: state goes to a partition labelled "hehenas-data" if present.
	cat > "$TARGET_DIR/etc/init.d/S01persist" <<'EOF'
#!/bin/sh
# Mount the partition labelled hehenas-data (if any) as persistent state.
[ "$1" = start ] || exit 0
DEV=$(findfs LABEL=hehenas-data 2>/dev/null)
if [ -n "$DEV" ]; then
	e2fsck -p "$DEV" >/dev/null 2>&1
	mount -o noatime "$DEV" /var/lib/hehenas && echo "persist: $DEV"
else
	echo "persist: no 'hehenas-data' partition — settings will be lost at shutdown"
fi
mkdir -p /var/lib/hehenas/etc
for f in /usr/share/hehenas/etc-default/*; do
	[ -e "/var/lib/hehenas/etc/${f##*/}" ] || cp "$f" /var/lib/hehenas/etc/
done
hostname -F /etc/hostname
EOF
	chmod 0755 "$TARGET_DIR/etc/init.d/S01persist"
	rm -f "$TARGET_DIR/etc/init.d/S00slot"
	;;
esac

# --- appliance hardening ----------------------------------------------------
# No password logins at all: root is locked (the console only shows the web
# address). Administration happens in the web UI; recovery uses flag files
# on the boot partition. Set HEHENAS_ROOT_CONSOLE=1 when building to keep a
# passwordless root console for debugging.
if [ "${HEHENAS_ROOT_CONSOLE:-0}" != 1 ] && [ -f "$TARGET_DIR/etc/shadow" ]; then
	sed -i 's/^root:[^:]*:/root:*:/' "$TARGET_DIR/etc/shadow"
fi
chmod 0600 "$TARGET_DIR/etc/shadow" 2>/dev/null || true
# Remove tools an appliance does not need that help an attacker.
rm -f "$TARGET_DIR/usr/bin/telnet" "$TARGET_DIR/usr/sbin/telnetd" "$TARGET_DIR/usr/bin/ftpget" "$TARGET_DIR/usr/bin/ftpput" \
	"$TARGET_DIR/usr/sbin/httpd" "$TARGET_DIR/usr/bin/nc" "$TARGET_DIR/bin/nc"

# Files from a Windows checkout may have lost their executable bit.
chmod 0755 "$TARGET_DIR"/etc/init.d/S* 2>/dev/null || true
