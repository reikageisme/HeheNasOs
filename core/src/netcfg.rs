//! Network configuration (DHCP / static IPv4), nftables firewall and hostname.
//!
//! Changes that can lock the admin out (IP, firewall) are applied with an
//! automatic rollback: unless the admin confirms from the new address within
//! `ROLLBACK_SECS`, the previous configuration is restored.

use std::{fmt::Write as _, fs, net::Ipv4Addr, path::Path};

use serde::{Deserialize, Serialize};

use crate::{config::Config, util};

pub const ROLLBACK_SECS: u64 = 120;

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(default)]
pub struct NetConfig {
    /// "dhcp" or "static"
    pub mode: String,
    /// "192.168.1.50/24"
    pub address: String,
    pub gateway: String,
    pub dns: Vec<String>,
}

impl Default for NetConfig {
    fn default() -> Self {
        Self { mode: "dhcp".into(), address: String::new(), gateway: String::new(), dns: Vec::new() }
    }
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq)]
#[serde(default)]
pub struct FwConfig {
    pub enabled: bool,
    /// Networks allowed to reach the web UI and file sharing.
    pub allowed: Vec<String>,
    pub smb: bool,
    pub nfs: bool,
}

impl Default for FwConfig {
    fn default() -> Self {
        // On by default: only private (LAN) ranges can reach the NAS at all.
        Self {
            enabled: true,
            allowed: vec!["192.168.0.0/16".into(), "10.0.0.0/8".into(), "172.16.0.0/12".into()],
            smb: true,
            nfs: true,
        }
    }
}

// ---- validation ------------------------------------------------------------------

fn parse_cidr(s: &str) -> Option<(Ipv4Addr, u8)> {
    let (ip, prefix) = match s.split_once('/') {
        Some((ip, p)) => (ip, p.parse::<u8>().ok()?),
        None => (s, 32),
    };
    let ip: Ipv4Addr = ip.parse().ok()?;
    (prefix <= 32).then_some((ip, prefix))
}

fn mask(prefix: u8) -> u32 {
    if prefix == 0 { 0 } else { u32::MAX << (32 - u32::from(prefix)) }
}

/// "192.168.1.7/24, 10.0.0.1" -> ["192.168.1.0/24", "10.0.0.1"]
pub fn normalize_cidrs(s: &str) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    for item in s.split(|c: char| c.is_whitespace() || c == ',').filter(|x| !x.is_empty()) {
        let (ip, prefix) = parse_cidr(item).ok_or_else(|| format!("Địa chỉ/mạng không hợp lệ: {item}"))?;
        let net = Ipv4Addr::from(u32::from(ip) & mask(prefix));
        out.push(if prefix == 32 { net.to_string() } else { format!("{net}/{prefix}") });
    }
    out.sort();
    out.dedup();
    if out.len() > 16 {
        return Err("Tối đa 16 mạng".into());
    }
    Ok(out)
}

pub fn validate_net(n: &NetConfig) -> Result<NetConfig, String> {
    let mut n = n.clone();
    match n.mode.as_str() {
        "dhcp" => Ok(NetConfig { mode: "dhcp".into(), ..Default::default() }),
        "static" => {
            let (ip, prefix) = parse_cidr(n.address.trim())
                .filter(|(_, p)| (8..=30).contains(p))
                .ok_or("Địa chỉ IP phải có dạng 192.168.1.50/24")?;
            n.address = format!("{ip}/{prefix}");
            n.gateway = n.gateway.trim().to_string();
            if !n.gateway.is_empty() {
                let gw: Ipv4Addr = n.gateway.parse().map_err(|_| "Gateway không hợp lệ")?;
                if u32::from(gw) & mask(prefix) != u32::from(ip) & mask(prefix) {
                    return Err("Gateway phải cùng mạng với địa chỉ IP".into());
                }
            }
            let mut dns = Vec::new();
            for d in n.dns.iter().map(|d| d.trim()).filter(|d| !d.is_empty()) {
                let a: Ipv4Addr = d.parse().map_err(|_| format!("DNS không hợp lệ: {d}"))?;
                dns.push(a.to_string());
            }
            dns.truncate(3);
            n.dns = dns;
            Ok(n)
        }
        _ => Err("Chế độ phải là dhcp hoặc static".into()),
    }
}

pub fn validate_fw(f: &FwConfig) -> Result<FwConfig, String> {
    let allowed = normalize_cidrs(&f.allowed.join(" "))?;
    if f.enabled && allowed.is_empty() {
        return Err("Cần ít nhất một mạng được phép, nếu không bạn sẽ tự khóa mình".into());
    }
    Ok(FwConfig { allowed, ..f.clone() })
}

pub fn validate_hostname(name: &str) -> Result<(), String> {
    let ok = !name.is_empty()
        && name.len() <= 63
        && name.chars().all(|c| c.is_ascii_alphanumeric() || c == '-')
        && !name.starts_with('-')
        && !name.ends_with('-');
    if ok { Ok(()) } else { Err("Tên máy chỉ gồm chữ, số và dấu - (tối đa 63 ký tự)".into()) }
}

// ---- rendering ---------------------------------------------------------------------

pub fn render_interfaces(cfg: &Config, n: &NetConfig) -> String {
    let mut o = String::from("# Generated by rustnasd\nauto lo\niface lo inet loopback\n\n");
    let _ = writeln!(o, "auto {}", cfg.net_iface);
    if n.mode == "static" {
        let (ip, prefix) = parse_cidr(&n.address).unwrap_or((Ipv4Addr::UNSPECIFIED, 24));
        let _ = writeln!(o, "iface {} inet static", cfg.net_iface);
        let _ = writeln!(o, "\taddress {ip}");
        let _ = writeln!(o, "\tnetmask {}", Ipv4Addr::from(mask(prefix)));
        if !n.gateway.is_empty() {
            let _ = writeln!(o, "\tgateway {}", n.gateway);
        }
        // Fixed command and paths only — never user data.
        let _ = writeln!(o, "\tup cp {} /etc/resolv.conf", cfg.resolv_static.display());
    } else {
        let _ = writeln!(o, "iface {} inet dhcp", cfg.net_iface);
    }
    o
}

pub fn render_resolv(n: &NetConfig) -> String {
    n.dns.iter().map(|d| format!("nameserver {d}\n")).collect()
}

pub fn render_nft(cfg: &Config, f: &FwConfig) -> String {
    let set = f.allowed.join(", ");
    let web = format!("{}, {}", Config::port_of(&cfg.listen), Config::port_of(&cfg.https_listen));
    let mut o = String::from("# Generated by rustnasd\ntable inet rustnas\ndelete table inet rustnas\n");
    o.push_str("table inet rustnas {\n\tchain input {\n");
    o.push_str("\t\ttype filter hook input priority filter; policy drop;\n");
    o.push_str("\t\tiif \"lo\" accept\n\t\tct state established,related accept\n\t\tct state invalid drop\n");
    o.push_str("\t\tmeta l4proto { icmp, ipv6-icmp } accept\n");
    o.push_str("\t\tudp sport 67 udp dport 68 accept\n");
    let _ = writeln!(o, "\t\tip saddr {{ {set} }} tcp dport {{ {web} }} accept");
    if f.smb {
        let _ = writeln!(o, "\t\tip saddr {{ {set} }} tcp dport 445 accept");
    }
    if f.nfs {
        let _ = writeln!(o, "\t\tip saddr {{ {set} }} tcp dport {{ 111, 2049, 20048 }} accept");
        let _ = writeln!(o, "\t\tip saddr {{ {set} }} udp dport {{ 111, 2049, 20048 }} accept");
    }
    o.push_str("\t}\n}\n");
    o
}

// ---- helper side --------------------------------------------------------------------

pub fn h_apply_network(cfg: &Config, n: &NetConfig) -> Result<String, String> {
    let n = validate_net(n)?;
    let content = render_interfaces(cfg, &n);
    let current = fs::read_to_string(&cfg.interfaces_file).unwrap_or_default();
    if n.mode == "static" {
        util::write_atomic(&cfg.resolv_static, render_resolv(&n).as_bytes(), 0o644)?;
    }
    if current == content {
        return Ok("unchanged".into());
    }
    util::write_atomic(&cfg.interfaces_file, content.as_bytes(), 0o644)?;
    crate::info!("network: applying {} config on {}", n.mode, cfg.net_iface);
    let _ = util::run(cfg.dry_run, "ifdown", &["-f", &cfg.net_iface]);
    util::run(cfg.dry_run, "ifup", &[&cfg.net_iface])?;
    Ok("applied".into())
}

pub fn h_apply_firewall(cfg: &Config, f: &FwConfig) -> Result<String, String> {
    let f = validate_fw(f)?;
    if !f.enabled {
        let _ = util::run(cfg.dry_run, "nft", &["delete", "table", "inet", "rustnas"]);
        let _ = fs::remove_file(&cfg.nft_file);
        return Ok("disabled".into());
    }
    util::write_atomic(&cfg.nft_file, render_nft(cfg, &f).as_bytes(), 0o644)?;
    let file = cfg.nft_file.to_string_lossy().into_owned();
    util::run(cfg.dry_run, "nft", &["-f", &file]).map(|_| "applied".into())
}

pub fn h_set_hostname(cfg: &Config, name: &str) -> Result<String, String> {
    validate_hostname(name)?;
    util::write_atomic(&cfg.hostname_file, format!("{name}\n").as_bytes(), 0o644)?;
    let hosts = fs::read_to_string(&cfg.hosts_file).unwrap_or_else(|_| "127.0.0.1\tlocalhost\n".into());
    let mut found = false;
    let mut out: Vec<String> = hosts
        .lines()
        .map(|l| {
            if l.starts_with("127.0.1.1") {
                found = true;
                format!("127.0.1.1\t{name}")
            } else {
                l.to_string()
            }
        })
        .collect();
    if !found {
        out.push(format!("127.0.1.1\t{name}"));
    }
    util::write_atomic(&cfg.hosts_file, (out.join("\n") + "\n").as_bytes(), 0o644)?;
    util::run(cfg.dry_run, "hostname", &[name])?;
    crate::info!("hostname changed to {name}");
    Ok(String::new())
}

// ---- persisted web-side state --------------------------------------------------------

fn load<T: for<'de> Deserialize<'de> + Default>(p: &Path) -> T {
    fs::read_to_string(p).ok().and_then(|s| toml::from_str(&s).ok()).unwrap_or_default()
}

fn save<T: Serialize>(p: &Path, v: &T) -> Result<(), String> {
    let s = toml::to_string(v).map_err(|e| e.to_string())?;
    util::write_atomic(p, s.as_bytes(), 0o600)
}

pub fn load_net(cfg: &Config) -> NetConfig {
    load(&cfg.state_dir.join("network.toml"))
}
pub fn save_net(cfg: &Config, n: &NetConfig) -> Result<(), String> {
    save(&cfg.state_dir.join("network.toml"), n)
}
pub fn load_fw(cfg: &Config) -> FwConfig {
    load(&cfg.state_dir.join("firewall.toml"))
}
pub fn save_fw(cfg: &Config, f: &FwConfig) -> Result<(), String> {
    save(&cfg.state_dir.join("firewall.toml"), f)
}

/// A change waiting for confirmation from the admin.
#[derive(Clone, Serialize)]
pub struct Pending {
    pub kind: String,
    #[serde(skip)]
    pub token: String,
    pub deadline: u64,
    #[serde(skip)]
    pub prev_net: Option<NetConfig>,
    #[serde(skip)]
    pub prev_fw: Option<FwConfig>,
    #[serde(skip)]
    pub new_net: Option<NetConfig>,
    #[serde(skip)]
    pub new_fw: Option<FwConfig>,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cidrs() {
        assert_eq!(normalize_cidrs("192.168.1.7/24, 10.0.0.1").unwrap(), vec!["10.0.0.1", "192.168.1.0/24"]);
        assert!(normalize_cidrs("300.1.1.1").is_err());
        assert!(normalize_cidrs("1.2.3.4/33").is_err());
        assert!(normalize_cidrs("").unwrap().is_empty());
    }

    #[test]
    fn static_net() {
        let ok = NetConfig { mode: "static".into(), address: "192.168.1.50/24".into(), gateway: "192.168.1.1".into(), dns: vec!["1.1.1.1".into()] };
        let n = validate_net(&ok).unwrap();
        let cfg = Config::default();
        let r = render_interfaces(&cfg, &n);
        assert!(r.contains("address 192.168.1.50\n\tnetmask 255.255.255.0\n\tgateway 192.168.1.1"));
        let bad = NetConfig { gateway: "10.0.0.1".into(), ..ok.clone() };
        assert!(validate_net(&bad).is_err());
        let bad = NetConfig { address: "192.168.1.50".into(), ..ok };
        assert!(validate_net(&bad).is_err());
    }

    #[test]
    fn nft() {
        let cfg = Config::default();
        let f = validate_fw(&FwConfig { enabled: true, ..Default::default() }).unwrap();
        let r = render_nft(&cfg, &f);
        assert!(r.contains("policy drop"));
        assert!(r.contains("tcp dport { 8080, 8443 } accept"));
        assert!(r.contains("tcp dport 445 accept"));
        assert!(validate_fw(&FwConfig { enabled: true, allowed: vec![], ..Default::default() }).is_err());
    }
}
